/**
 * 「出击准备」面板的**引擎无关真源**（V6.41）。
 *
 * ---------------------------------------------------------------------------
 * 为什么主界面要多一道「出击准备」
 * ---------------------------------------------------------------------------
 * 用户原话：「主界面**开始下潜**感觉安排到**右下角一个开始游戏 IcoN** 里面；
 * 选择机体和首个机枪，**进入游戏给个选项**，比较合适吧」。
 *
 * 版式上这是把主界面从"功能罗列"改成 **hub（分流器）**：
 *   · 主界面上**只有一个动作** —— 右下角的「开始游戏」；
 *   · 左右分类栏全是"看/管"（图鉴 / 里程碑 / 装置坞 / 海域）；
 *   · 中央腾出来做**船坞待机动画**（原来放的是机体选择器）。
 * 于是"选哪台艇、带哪把枪"整体后移到**出击准备**这一步，正好也符合
 * "先看装备、再下潜"的流程直觉。
 *
 * ---------------------------------------------------------------------------
 * 为什么候选清单放在 shared 而不是写在视图层
 * ---------------------------------------------------------------------------
 * 与 `menu.ts` 的入口表同一个理由：**加/换一把开局武器 = 改一行数据**，
 * 视图层只负责排布与选中态。写死在 `Title.ts` 里的话，Phaser 侧要用就得再抄一份 ——
 * 而两份清单漂移的症状是"某个武器在某端选不到"，它不会报错。
 */
import type { WeaponId } from './types'

/**
 * 开局可选的第一个武器。
 *
 * **为什么恰好是这 4 把**：它们是 `WEAPON_DEF` 里的**四个基础族**
 * （声呐 / 机关枪 / 鱼雷 / 电弧），每族在商店里都有 2 条进化线 ——
 * 所以选谁只是"开局倾向"，不会锁死 build。
 * `gun_gl` / `sonar_rs` / `torp_hv` 这些是**进化形态**，不能当开局武器。
 *
 * 顺序 = 面板上的排列顺序。声呐排第一是因为它的"环形波前"最能表达
 * 本作"声呐"的题材内核，也最适合教学层（L1 阳光带）。
 */
export const START_WEAPONS: readonly WeaponId[] = ['sonar', 'gun', 'torpedo', 'arc']

/**
 * 没指定时的开局武器。
 *
 * 取 `gun`（脉冲机关枪）而不是列表第一项 —— 它是原版一直用的开局武器
 * （`world.ts` 里那句 `this.addWeapon('gun')`），换成声呐会改变所有
 * 已有存档玩家的第一局手感，属于"没人要求过的改动"。
 */
export const DEFAULT_START_WEAPON: WeaponId = 'gun'

/** 在 `START_WEAPONS` 里找下标；找不到 / 未定义时回落到默认武器。 */
export function startWeaponIndex(id: WeaponId | undefined): number {
  const i = START_WEAPONS.indexOf(id as WeaponId)
  return i >= 0 ? i : START_WEAPONS.indexOf(DEFAULT_START_WEAPON)
}
